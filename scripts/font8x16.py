"""VOS early-boot font (U1): an original 8x16 bitmap font for printable ASCII.

Drawn for VOS; no glyph is copied from another font. It is only for
kernel diagnostics (the framebuffer console) and is independent of any
later VOS display font. Every glyph is 16 rows of 8 columns ('#' = on):
capitals use rows 3-11, lower case rows 6-11, descenders reach row 14,
and column 7 stays blank so that neighbouring glyphs never touch.

    python3 -I scripts/font8x16.py > arch/x86_64/font8x16.c

regenerates the C table; the x86_64 test target checks that the committed
file is exactly this script's output.
"""
import sys

B = "........"

G = {}


def glyph(ch, *rows):
    """rows: the glyph's rows from row 3 down (missing rows are blank)."""
    full = [B] * 3 + list(rows)
    full += [B] * (16 - len(full))
    assert len(full) == 16, (ch, len(full))
    for r in full:
        assert len(r) == 8 and set(r) <= {"#", "."}, (ch, r)
        assert r[7] == ".", (ch, "column 7 must stay blank")
    G[ch] = full


