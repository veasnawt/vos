def main():
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in G]
    assert not missing, missing
    out = sys.stdout
    out.write("/*\n * VOS early-boot font (U1): an original 8x16 bitmap font for printable ASCII,\n")
    out.write(" * generated by scripts/font8x16.py (the glyph art is the source; do not edit).\n")
    out.write(" * Row r of glyph c is font8x16[c - 0x20][r]; bit 7 is the leftmost pixel.\n */\n")
    out.write('#include "font8x16.h"\n\n')
    out.write("const uint8_t font8x16[FONT8X16_GLYPHS][16] = {\n")
    for c in range(0x20, 0x7F):
        rows = G[chr(c)]
        vals = ", ".join("0x%02X" % int(r.replace("#", "1").replace(".", "0"), 2) for r in rows)
        name = {"\\": "backslash", "'": "quote", " ": "space"}.get(chr(c), chr(c))
        out.write("    { %s },  /* 0x%02X %s */\n" % (vals, c, name))
    out.write("};\n")


if __name__ == "__main__":
    main()
